class LlmClient:
    def __init__(self, config: Config) -> None:
        self.config = config
        api_key = os.environ.get(config.api_key_env, "").strip()
        if not api_key:
            raise RuntimeError(f"Environment variable {config.api_key_env} is not set")
        self.api_key = api_key

    def chat_json(self, messages: List[Dict[str, str]], schema: Dict[str, Any], purpose: str) -> Dict[str, Any]:
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }

        last_error = ""
        response_format_mode = "json_schema" if self.config.use_response_format else "json_object"
        for attempt in range(1, self.config.max_http_retries + 3):
            payload = self._payload(messages, schema, response_format_mode)
            body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
            req = urllib.request.Request(self.config.api_url, data=body, headers=headers, method="POST")
            try:
                with urllib.request.urlopen(req, timeout=self.config.request_timeout_sec) as resp:
                    raw = resp.read().decode("utf-8")
                parsed = json.loads(raw)
                content = parsed["choices"][0]["message"].get("content", "")
                text = self._content_to_text(content)
                return extract_json_object(text)
            except urllib.error.HTTPError as exc:
                error_body = exc.read().decode("utf-8", errors="replace")
                last_error = f"HTTP {exc.code}: {error_body[:2000]}"
                if exc.code in {400, 422} and response_format_mode in {"json_schema", "json_object"}:
                    rejected_mode = response_format_mode
                    response_format_mode = "json_object" if response_format_mode == "json_schema" else "none"
                    print_log(
                        f"LLM {purpose}: provider rejected {rejected_mode} response format; "
                        f"retrying with {response_format_mode}"
                    )
                    continue
                if exc.code in {408, 409, 429, 500, 502, 503, 504}:
                    sleep_for = min(60.0, 2**attempt + random.random())
                    print_log(f"LLM {purpose}: transient error {exc.code}, retry {attempt}/{self.config.max_http_retries}")
                    time.sleep(sleep_for)
                    continue
                raise RuntimeError(last_error) from exc
            except Exception as exc:
                last_error = f"{type(exc).__name__}: {exc}"
                if attempt < self.config.max_http_retries:
                    sleep_for = min(30.0, 2**attempt + random.random())
                    print_log(f"LLM {purpose}: error, retry {attempt}/{self.config.max_http_retries}: {last_error}")
                    time.sleep(sleep_for)
                    continue
                raise RuntimeError(last_error) from exc
        raise RuntimeError(last_error or "LLM request failed")

    def _payload(self, messages: List[Dict[str, str]], schema: Dict[str, Any], response_format_mode: str) -> Dict[str, Any]:
        effective_messages = messages
        if response_format_mode != "json_schema":
            effective_messages = [
                *messages,
                {
                    "role": "user",
                    "content": "Return JSON conforming to this JSON Schema:\n" + safe_json(schema, max_chars=30_000),
                },
            ]

        payload: Dict[str, Any] = {
            "model": self.config.model,
            "messages": effective_messages,
            "temperature": self.config.temperature,
            "max_tokens": self.config.max_tokens,
        }
        if response_format_mode == "json_schema":
            payload["response_format"] = {"type": "json_schema", "json_schema": schema}
        elif response_format_mode == "json_object":
            payload["response_format"] = {"type": "json_object"}
        return payload

    @staticmethod
    def _content_to_text(content: Any) -> str:
        if isinstance(content, str):
            return content
        if isinstance(content, list):
            parts: List[str] = []
            for item in content:
                if isinstance(item, dict):
                    if item.get("type") in {"text", "output_text"}:
                        parts.append(str(item.get("text", "")))
                    elif "content" in item:
                        parts.append(str(item["content"]))
                else:
                    parts.append(str(item))
            return "\n".join(parts)
        return str(content)


def extract_json_object(text: str) -> Dict[str, Any]:
    stripped = text.strip()
    if stripped.startswith("```"):
        stripped = re.sub(r"^```(?:json)?", "", stripped, flags=re.I).strip()
        stripped = re.sub(r"```$", "", stripped).strip()
    try:
        obj = json.loads(stripped)
    except json.JSONDecodeError:
        start = stripped.find("{")
        end = stripped.rfind("}")
        if start == -1 or end == -1 or end <= start:
            raise
        obj = json.loads(stripped[start : end + 1])
    if not isinstance(obj, dict):
        raise ValueError("LLM response must be a JSON object")
    return obj


