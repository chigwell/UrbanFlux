def add_rule_note(rule: MutableMapping[str, Any], note: str) -> None:
    evidence = rule.get("evidence", [])
    if not isinstance(evidence, list):
        evidence = []
    marker = f"deterministic_preflight: {note}"
    if marker not in evidence:
        evidence.append(marker)
    rule["evidence"] = evidence
    existing_notes = str(rule.get("notes") or "")
    if note not in existing_notes:
        rule["notes"] = normalize_space((existing_notes + " " + marker).strip())


def harden_rule_for_detected_structure(
    cleaned: Dict[str, Any],
    table: PreparedTable,
    record: Optional[FileRecord] = None,
) -> Dict[str, Any]:
    # The LLM can ignore its own instructions. These deterministic guards fix
    # two high-impact classes of mistakes before validation/application:
    # 1) collapsing row-level borough values to a constant London-wide area;
    # 2) leaving wide date-coded measure columns in annotate_rows mode.
    area_candidates = detect_row_area_columns(table)
    if area_candidates and cleaned["area_rule"]["strategy"] in {"constant", "filename", "source_description", "none"}:
        best = area_candidates[0]
        cleaned["area_rule"].update(
            {
                "strategy": "row_column",
                "columns": [best["column"]],
                "regex": "",
                "constant_kind": "",
                "constant_name": "",
                "constant_raw": "",
                "allow_custom_area": True,
                "reason_when_missing": "",
            }
        )
        add_rule_note(
            cleaned,
            f"row-level geography column {best['column']!r} has multiple recognised borough/area values; using row_column instead of dataset-level area.",
        )

    date_candidates = detect_date_header_columns(table, record=record)
    configured_unpivot_columns = {
        str(item.get("column") or "")
        for item in cleaned.get("unpivot", {}).get("columns", [])
        if isinstance(item, Mapping)
    }
    needs_date_unpivot = len(date_candidates) >= 2 and not configured_unpivot_columns.issuperset(
        {str(item["column"]) for item in date_candidates}
    )
    if needs_date_unpivot:
        cleaned["output_mode"] = "unpivot_date_columns"
        cleaned["unpivot"]["enabled"] = True
        cleaned["unpivot"]["drop_empty_values"] = True
        cleaned["unpivot"]["columns"] = [
            {
                "column": str(item["column"]),
                "measure_name": str(item["measure_name"]),
                "date_raw": str(item["date_raw"]),
                "area_raw": "",
            }
            for item in date_candidates
        ]
        add_rule_note(
            cleaned,
            f"detected {len(date_candidates)} date-bearing measure headers; enabled unpivot_date_columns.",
        )

    if cleaned.get("unpivot", {}).get("enabled") and detect_date_header_columns(table, record=record):
        if cleaned["date_rule"]["strategy"] != "from_unpivot_column":
            cleaned["date_rule"].update(
                {
                    "strategy": "from_unpivot_column",
                    "columns": [],
                    "regex": "",
                    "constant_start": "",
                    "constant_end": "",
                    "constant_raw": "",
                    "reason_when_missing": "",
                }
            )
            add_rule_note(cleaned, "using date_rule.strategy=from_unpivot_column because unpivoted headers carry date semantics.")
        if preferred_date_interpretation(record) == "uk_census_day" and cleaned["date_rule"].get("interpretation") in {"", "auto", "calendar"}:
            cleaned["date_rule"]["interpretation"] = "uk_census_day"
            add_rule_note(cleaned, "using uk_census_day interpretation for Census-year measure headers.")

    return cleaned


def validate_rule(
    rule: Mapping[str, Any],
    raw: RawCsv,
    record: Optional[FileRecord] = None,
) -> Tuple[Dict[str, Any], List[Dict[str, Any]], PreparedTable]:
    cleaned = clean_rule(rule)
    errors: List[Dict[str, Any]] = []

    if cleaned["decision"] not in {"apply", "quarantine_file"}:
        errors.append({"field": "decision", "message": "decision must be apply or quarantine_file"})
    if cleaned["output_mode"] not in {
        "annotate_rows",
        "unpivot_date_columns",
        "unpivot_area_columns",
        "unpivot_date_area_columns",
    }:
        errors.append({"field": "output_mode", "message": "unsupported output_mode"})

    table = prepare_table(raw, cleaned["layout"])
    cleaned = harden_rule_for_detected_structure(cleaned, table, record=record)
    headers = set(table.headers)

    date_strategy = cleaned["date_rule"]["strategy"]
    if date_strategy not in {"row_column", "filename", "source_description", "constant_range", "from_unpivot_column", "none"}:
        errors.append({"field": "date_rule.strategy", "message": f"unsupported strategy {date_strategy}"})
    if date_strategy == "row_column":
        missing = [col for col in cleaned["date_rule"]["columns"] if col not in headers]
        if missing:
            errors.append(
                {
                    "field": "date_rule.columns",
                    "message": f"missing columns: {missing}",
                    "available_headers": table.headers,
                }
            )
    if date_strategy == "constant_range":
        start = cleaned["date_rule"]["constant_start"]
        end = cleaned["date_rule"]["constant_end"]
        if start or end:
            if not parse_iso_date(start) or not parse_iso_date(end):
                errors.append({"field": "date_rule.constant_range", "message": "constant_start/end must be ISO YYYY-MM-DD"})
        elif not cleaned["date_rule"]["constant_raw"]:
            errors.append({"field": "date_rule.constant_raw", "message": "constant_range requires constant_start/end or constant_raw"})
    if date_strategy == "none" and not cleaned["date_rule"]["reason_when_missing"]:
        errors.append({"field": "date_rule.reason_when_missing", "message": "strategy none requires a precise reason"})

    area_strategy = cleaned["area_rule"]["strategy"]
    if area_strategy not in {"row_column", "filename", "source_description", "constant", "from_unpivot_column", "none"}:
        errors.append({"field": "area_rule.strategy", "message": f"unsupported strategy {area_strategy}"})
    if area_strategy == "row_column":
        missing = [col for col in cleaned["area_rule"]["columns"] if col not in headers]
        if missing:
            errors.append(
                {
                    "field": "area_rule.columns",
                    "message": f"missing columns: {missing}",
                    "available_headers": table.headers,
                }
            )
    if area_strategy == "constant":
        if cleaned["area_rule"]["constant_kind"] not in AREA_KINDS:
            errors.append({"field": "area_rule.constant_kind", "message": "unsupported area kind"})
        if cleaned["area_rule"]["constant_kind"] != "no_specific_area" and not cleaned["area_rule"]["constant_name"]:
            errors.append({"field": "area_rule.constant_name", "message": "constant area requires constant_name"})
    if area_strategy == "none" and not cleaned["area_rule"]["reason_when_missing"]:
        errors.append({"field": "area_rule.reason_when_missing", "message": "strategy none requires a precise reason"})

    if cleaned["unpivot"]["enabled"]:
        if not cleaned["unpivot"]["columns"]:
            errors.append({"field": "unpivot.columns", "message": "unpivot enabled but no columns provided"})
        missing_unpivot = [item["column"] for item in cleaned["unpivot"]["columns"] if item["column"] not in headers]
        if missing_unpivot:
            errors.append(
                {
                    "field": "unpivot.columns",
                    "message": f"missing unpivot columns: {missing_unpivot}",
                    "available_headers": table.headers,
                }
            )
    else:
        if cleaned["output_mode"] != "annotate_rows":
            errors.append({"field": "unpivot.enabled", "message": "unpivot output_mode requires unpivot.enabled = true"})

    return cleaned, errors, table


def apply_regex_if_any(value: str, regex: str, group_name: str) -> str:
    if not regex.strip():
        return value
    try:
        match = re.search(regex, value, re.I | re.S)
    except re.error:
        return value
    if not match:
        return ""
    if group_name in match.groupdict():
        return normalize_space(match.group(group_name) or "")
    if match.groups():
        return normalize_space(match.group(1) or "")
    return normalize_space(match.group(0) or "")


def select_first_row_value(row: Mapping[str, str], columns: Sequence[str]) -> Tuple[str, str]:
    for column in columns:
        value = normalize_space(row.get(column, ""))
        if value:
            return value, column
    return "", ""


def resolve_date(
    date_rule: Mapping[str, Any],
    row: Mapping[str, str],
    record: FileRecord,
    unit: Mapping[str, str],
) -> DateResolution:
    strategy = str(date_rule.get("strategy") or "none")
    interpretation = str(date_rule.get("interpretation") or "auto")
    dayfirst = bool(date_rule.get("dayfirst", True))
    reason = str(date_rule.get("reason_when_missing") or "")
    regex = str(date_rule.get("regex") or "")

    raw = ""
    source = strategy

    if strategy == "none":
        return date_resolution_no_date("", "none", reason)
    if strategy == "row_column":
        raw, source_column = select_first_row_value(row, list(date_rule.get("columns", [])))
        source = f"row_column:{source_column}" if source_column else "row_column"
    elif strategy == "filename":
        raw = record.file_path.name
        source = "filename"
    elif strategy == "source_description":
        raw = record.source_description
        source = "source_description"
    elif strategy == "from_unpivot_column":
        raw = unit.get("date_raw", "") or unit.get("measure_column", "")
        source = f"unpivot_column:{unit.get('measure_column', '')}"
    elif strategy == "constant_range":
        start_text = str(date_rule.get("constant_start") or "")
        end_text = str(date_rule.get("constant_end") or "")
        raw = str(date_rule.get("constant_raw") or f"{start_text} - {end_text}")
        if start_text and end_text:
            start = parse_iso_date(start_text)
            end = parse_iso_date(end_text)
            if start and end and end >= start:
                precision = str(date_rule.get("precision") or "date_range")
                return make_date_resolution(start, end, precision, raw, "constant_range", "Used constant date range from rule.")
        source = "constant_range"
    else:
        return date_resolution_no_date("", strategy, f"Unsupported date strategy {strategy}")

    raw = apply_regex_if_any(raw, regex, "date")
    if not raw:
        return date_resolution_no_date(raw, source, reason)
    return parse_date_range(raw, source=source, interpretation=interpretation, dayfirst=dayfirst, reason_when_missing=reason)


def resolve_area(
    area_rule: Mapping[str, Any],
    row: Mapping[str, str],
    record: FileRecord,
    unit: Mapping[str, str],
) -> AreaResolution:
    strategy = str(area_rule.get("strategy") or "none")
    reason = str(area_rule.get("reason_when_missing") or "")
    regex = str(area_rule.get("regex") or "")
    allow_custom = bool(area_rule.get("allow_custom_area", True))

    if strategy == "none":
        return AreaResolution(
            kind="no_specific_area",
            name="",
            raw="",
            source="none",
            reason=reason or "No area is available in row, headers, filename, or source description.",
            confidence=1.0,
        )

    raw = ""
    source = strategy
    if strategy == "constant":
        kind = str(area_rule.get("constant_kind") or "no_specific_area")
        name = str(area_rule.get("constant_name") or "")
        raw = str(area_rule.get("constant_raw") or name)
        if kind == "london_borough":
            normalized = normalize_area_text(name or raw, allow_custom_area=False)
            if normalized.kind == "london_borough":
                normalized.raw = raw
                normalized.source = "constant"
                return normalized
        if kind == "city_of_london":
            return AreaResolution(kind, CITY_OF_LONDON, raw, "constant", "Used constant City of London area from rule.", 1.0)
        if kind == "london_all":
            return AreaResolution(kind, "London", raw, "constant", "Used constant London-wide area from rule.", 1.0)
        if kind == "uk_all":
            return AreaResolution(kind, "United Kingdom", raw, "constant", "Used constant UK-wide area from rule.", 1.0)
        if kind == "england_all":
            return AreaResolution(kind, "England", raw, "constant", "Used constant England-wide area from rule.", 1.0)
        if kind == "custom_london_area":
            return AreaResolution(kind, name or raw, raw, "constant", "Used custom London area from rule.", 0.7)
        return AreaResolution("no_specific_area", "", raw, "constant", reason or "Rule declares no specific area.", 1.0)
    if strategy == "row_column":
        raw, source_column = select_first_row_value(row, list(area_rule.get("columns", [])))
        source = f"row_column:{source_column}" if source_column else "row_column"
    elif strategy == "filename":
        raw = record.file_path.name
        source = "filename"
    elif strategy == "source_description":
        raw = record.source_description
        source = "source_description"
    elif strategy == "from_unpivot_column":
        raw = unit.get("area_raw", "") or unit.get("measure_column", "")
        source = f"unpivot_column:{unit.get('measure_column', '')}"
    else:
        return AreaResolution("no_specific_area", "", "", strategy, f"Unsupported area strategy {strategy}", 0.0)

    raw = apply_regex_if_any(raw, regex, "area")
    if not raw:
        return AreaResolution(
            kind="no_specific_area",
            name="",
            raw="",
            source=source,
            reason=reason or "No area text found in selected source.",
            confidence=1.0,
        )

    normalized = normalize_area_text(raw, allow_custom_area=allow_custom)
    normalized.source = source
    if normalized.kind == "no_specific_area" and reason:
        normalized.reason = reason
    return normalized


def build_units(row: Mapping[str, str], rule: Mapping[str, Any]) -> Tuple[List[Dict[str, str]], List[Dict[str, Any]]]:
    unpivot = rule.get("unpivot", {}) if isinstance(rule.get("unpivot"), Mapping) else {}
    if not unpivot.get("enabled"):
        return [
            {
                "measure_column": "",
                "measure_name": "",
                "measure_value": "",
                "date_raw": "",
                "area_raw": "",
            }
        ], []

    units: List[Dict[str, str]] = []
    skipped: List[Dict[str, Any]] = []
    drop_empty = bool(unpivot.get("drop_empty_values", True))
    for item in unpivot.get("columns", []):
        if not isinstance(item, Mapping):
            continue
        column = str(item.get("column") or "")
        value = normalize_space(row.get(column, ""))
        if drop_empty and value == "":
            continue
        units.append(
            {
                "measure_column": column,
                "measure_name": str(item.get("measure_name") or column),
                "measure_value": value,
                "date_raw": str(item.get("date_raw") or ""),
                "area_raw": str(item.get("area_raw") or ""),
            }
        )
    if not units:
        skipped.append(
            {
                "raw_row_number": row.get("_normalizer_raw_row_number", ""),
                "reason": "all configured unpivot value columns were empty",
            }
        )
    return units, skipped


def validate_output_row(row: Mapping[str, str]) -> List[str]:
    errors: List[str] = []
    date_status = row.get("_normalizer_date_status", "")
    if date_status not in DATE_STATUSES:
        errors.append(f"invalid date status {date_status!r}")
    if date_status == "resolved":
        start = parse_iso_date(row.get("_normalizer_date_start", ""))
        end = parse_iso_date(row.get("_normalizer_date_end", ""))
        if not start or not end:
            errors.append("resolved date requires valid ISO date_start/date_end")
        elif end < start:
            errors.append("date_end is before date_start")
    if date_status == "no_date_in_available_context" and not row.get("_normalizer_date_reason", ""):
        errors.append("no-date rows require _normalizer_date_reason")

    area_kind = row.get("_normalizer_area_kind", "")
    if area_kind not in AREA_KINDS:
        errors.append(f"invalid area kind {area_kind!r}")
    if area_kind in {"london_borough", "city_of_london", "london_all", "uk_all", "england_all", "custom_london_area"}:
        if not row.get("_normalizer_area_name", ""):
            errors.append(f"area kind {area_kind} requires _normalizer_area_name")
    if area_kind == "london_borough" and row.get("_normalizer_area_name") not in CANONICAL_BOROUGHS:
        errors.append("london_borough area_name is not in canonical borough list")
    if area_kind == "city_of_london" and row.get("_normalizer_area_name") != CITY_OF_LONDON:
        errors.append("city_of_london area_name must be City of London")
    if area_kind == "london_all" and row.get("_normalizer_area_name") != "London":
        errors.append("london_all area_name must be London")
    if area_kind == "uk_all" and row.get("_normalizer_area_name") != "United Kingdom":
        errors.append("uk_all area_name must be United Kingdom")
    if area_kind == "england_all" and row.get("_normalizer_area_name") != "England":
        errors.append("england_all area_name must be England")
    if area_kind == "no_specific_area" and not row.get("_normalizer_area_reason", ""):
        errors.append("no_specific_area requires _normalizer_area_reason")
    return errors


def apply_rule_to_csv(
    raw: RawCsv,
    table: PreparedTable,
    rule: Mapping[str, Any],
    record: FileRecord,
    attempt: int,
    max_validation_errors: int,
) -> ApplyResult:
    output_rows: List[OrderedDict[str, str]] = []
    validation_errors: List[Dict[str, Any]] = []
    skipped_rows: List[Dict[str, Any]] = list(table.skipped_raw_rows)
    current_rule_hash = rule_hash(rule)

    if rule.get("decision") == "quarantine_file":
        validation_errors.append(
            {
                "level": "file",
                "message": "LLM rule requested quarantine_file",
                "notes": rule.get("notes", ""),
                "evidence": rule.get("evidence", []),
            }
        )
        return ApplyResult(output_rows, validation_errors, skipped_rows, table.headers, len(table.rows))

    for row_index, row in enumerate(table.rows, start=1):
        units, unit_skips = build_units(row, rule)
        skipped_rows.extend(unit_skips)
        if not units:
            continue

        for unit in units:
            date_res = resolve_date(rule["date_rule"], row, record, unit)
            area_res = resolve_area(rule["area_rule"], row, record, unit)
            out: OrderedDict[str, str] = OrderedDict()
            for key, value in row.items():
                if key == "_normalizer_raw_row_number":
                    continue
                out[key] = value
            out.update(
                {
                    "_normalizer_status": "ok",
                    "_normalizer_errors": "",
                    "_normalizer_input_file": str(record.file_path),
                    "_normalizer_source_id": record.source_id,
                    "_normalizer_source_file_id": record.source_file_id,
                    "_normalizer_input_row_number": row.get("_normalizer_raw_row_number", str(row_index)),
                    "_normalizer_output_row_number": str(len(output_rows) + 1),
                    "_normalizer_rule_attempt": str(attempt),
                    "_normalizer_rule_hash": current_rule_hash,
                    "_normalizer_measure_column": unit.get("measure_column", ""),
                    "_normalizer_measure_name": unit.get("measure_name", ""),
                    "_normalizer_measure_value": unit.get("measure_value", ""),
                    "_normalizer_date_status": date_res.status,
                    "_normalizer_date_start": date_res.start,
                    "_normalizer_date_end": date_res.end,
                    "_normalizer_date_precision": date_res.precision,
                    "_normalizer_date_raw": date_res.raw,
                    "_normalizer_date_source": date_res.source,
                    "_normalizer_date_reason": date_res.reason,
                    "_normalizer_area_kind": area_res.kind,
                    "_normalizer_area_name": area_res.name,
                    "_normalizer_area_raw": area_res.raw,
                    "_normalizer_area_source": area_res.source,
                    "_normalizer_area_reason": area_res.reason,
                    "_normalizer_confidence": f"{min(float(rule.get('confidence') or 0.0), area_res.confidence):.3f}",
                }
            )
            row_errors = validate_output_row(out)
            if row_errors:
                out["_normalizer_status"] = "error"
                out["_normalizer_errors"] = "; ".join(row_errors)
                if len(validation_errors) < max_validation_errors:
                    validation_errors.append(
                        {
                            "raw_row_number": out["_normalizer_input_row_number"],
                            "measure_column": out["_normalizer_measure_column"],
                            "errors": row_errors,
                            "row_sample": {key: truncate(value, 120) for key, value in out.items() if value},
                        }
                    )
            output_rows.append(out)

    if not output_rows and table.rows:
        validation_errors.append(
            {
                "level": "file",
                "message": "Rule produced zero output rows for a non-empty prepared table",
                "input_data_row_count": len(table.rows),
            }
        )

    return ApplyResult(output_rows, validation_errors, skipped_rows, table.headers, len(table.rows))


def output_paths(record: FileRecord, fingerprint: str, out_dir: Path) -> Tuple[Path, Path, Path]:
    safe_stem = re.sub(r"[^A-Za-z0-9._-]+", "_", record.file_path.stem)[:100] or "csv"
    short = hashlib.sha256(f"{record.source_id}:{record.source_file_id}:{record.file_path}".encode("utf-8")).hexdigest()[:12]
    base = out_dir / f"{safe_stem}.{short}.{fingerprint[:10]}"
    return (
        base.with_suffix(".normalized.csv"),
        base.with_suffix(".quarantine.jsonl"),
        base.with_suffix(".skipped.jsonl"),
    )


def write_jsonl(path: Path, rows: Sequence[Mapping[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False, default=str) + "\n")


def write_normalized_csv(path: Path, rows: Sequence[Mapping[str, str]], prepared_headers: Sequence[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    headers: List[str] = []
    for header in prepared_headers:
        if header not in headers:
            headers.append(header)
    for row in rows:
        for key in row.keys():
            if key not in headers and key not in OUTPUT_COLUMNS:
                headers.append(key)
    for column in OUTPUT_COLUMNS:
        if column not in headers:
            headers.append(column)

    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=headers, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def validation_payload(
    rule_errors: Sequence[Mapping[str, Any]],
    apply_result: Optional[ApplyResult] = None,
    verifier_result: Optional[Mapping[str, Any]] = None,
) -> Dict[str, Any]:
    payload: Dict[str, Any] = {
        "rule_error_count": len(rule_errors),
        "rule_errors": list(rule_errors)[:20],
    }
    if apply_result is not None:
        payload["apply_summary"] = summarize_validation(apply_result)
    if verifier_result is not None:
        payload["verifier_result"] = verifier_result
    return payload


def previous_attempt_summary(
    attempt: int,
    rule: Mapping[str, Any],
    validation: Mapping[str, Any],
) -> Dict[str, Any]:
    return {
        "attempt": attempt,
        "rule_hash": rule_hash(rule),
        "rule": rule,
        "validation": validation,
    }


def process_one_file(config: Config, llm: LlmClient, record: FileRecord, conn: sqlite3.Connection) -> str:
    key = file_key(record)
    if not record.file_path.exists():
        msg = f"File does not exist: {record.file_path}"
        upsert_file_state(conn, key, record, "missing", "missing_file", 0, last_error=msg)
        print_log(msg)
        return "missing_file"

    fingerprint = sha256_file(record.file_path)
    state = get_file_state(conn, key)
    if state and not config.force:
        if state["fingerprint"] == fingerprint and state["status"] == "done":
            return "skipped_done"
        if state["fingerprint"] == fingerprint and state["status"] == "failed" and int(state["attempts"]) >= config.max_rule_attempts:
            return "skipped_failed"

    print_log(f"Processing {record.file_path}")
    upsert_file_state(conn, key, record, fingerprint, "processing", 0)
    raw = read_csv_raw(record.file_path, config.encodings)
    initial_table = prepare_table(raw)

    attempts_history: List[Dict[str, Any]] = []
    last_error_message = ""
    final_quarantine_path = ""

    for attempt in range(1, config.max_rule_attempts + 1):
        profile = build_csv_profile(record, raw, initial_table, config, previous_attempts=attempts_history)
        try:
            rule = infer_rule(llm, profile)
            cleaned_rule, rule_errors, table = validate_rule(rule, raw, record=record)
            if rule_errors:
                validation = validation_payload(rule_errors)
                insert_rule_history(conn, key, attempt, cleaned_rule, validation)
                attempts_history.append(previous_attempt_summary(attempt, cleaned_rule, validation))
                last_error_message = f"rule validation failed: {rule_errors[:3]}"
                print_log(f"Attempt {attempt}: rule validation failed for {record.file_path.name}")
                continue

            apply_result = apply_rule_to_csv(raw, table, cleaned_rule, record, attempt, config.max_validation_errors)
            verifier_result: Dict[str, Any] = {}
            if apply_result.validation_errors:
                validation = validation_payload([], apply_result)
                insert_rule_history(conn, key, attempt, cleaned_rule, validation)
                attempts_history.append(previous_attempt_summary(attempt, cleaned_rule, validation))
                last_error_message = f"output validation failed: {apply_result.validation_errors[:3]}"
                print_log(f"Attempt {attempt}: output validation failed for {record.file_path.name}")
                continue

            if config.verify_with_llm:
                try:
                    verifier_profile = build_csv_profile(record, raw, table, config, previous_attempts=attempts_history)
                    verifier_result = verify_rule_with_llm(llm, verifier_profile, cleaned_rule, apply_result, config)
                    approved = bool(verifier_result.get("approved"))
                    confidence = float(verifier_result.get("confidence") or 0.0)
                    if not approved or confidence < config.verifier_confidence_threshold:
                        validation = validation_payload([], apply_result, verifier_result)
                        insert_rule_history(conn, key, attempt, cleaned_rule, validation, verifier_result)
                        attempts_history.append(previous_attempt_summary(attempt, cleaned_rule, validation))
                        last_error_message = f"LLM verifier rejected rule: {verifier_result}"
                        print_log(f"Attempt {attempt}: LLM verifier rejected {record.file_path.name}")
                        continue
                except Exception as exc:
                    if config.fail_on_llm_verifier_error:
                        raise
                    verifier_result = {
                        "approved": True,
                        "confidence": 0.0,
                        "errors": [],
                        "notes": f"Verifier failed but fail_on_llm_verifier_error is false: {exc}",
                    }

            validation = validation_payload([], apply_result, verifier_result if verifier_result else None)
            insert_rule_history(conn, key, attempt, cleaned_rule, validation, verifier_result)

            normalized_path, quarantine_path, skipped_path = output_paths(record, fingerprint, config.out_dir)
            if not config.dry_run:
                write_normalized_csv(normalized_path, apply_result.output_rows, apply_result.prepared_headers)
                if apply_result.skipped_rows:
                    write_jsonl(skipped_path, apply_result.skipped_rows)
            upsert_file_state(
                conn,
                key,
                record,
                fingerprint,
                "done",
                attempt,
                output_path=str(normalized_path),
                quarantine_path="",
                last_error="",
            )
            print_log(f"Done {record.file_path.name}: {len(apply_result.output_rows)} output rows -> {normalized_path}")
            return "done"
        except Exception as exc:
            last_error_message = f"{type(exc).__name__}: {exc}\n{traceback.format_exc()}"
            log_event(conn, key, "attempt_exception", last_error_message[:4000])
            attempts_history.append(
                {
                    "attempt": attempt,
                    "exception": truncate(last_error_message, 4000),
                    "instruction": "Fix the rule or layout so the next attempt avoids this exception.",
                }
            )
            print_log(f"Attempt {attempt}: exception for {record.file_path.name}: {exc}")
            continue

    normalized_path, quarantine_path, skipped_path = output_paths(record, fingerprint, config.out_dir)
    final_quarantine_path = str(quarantine_path)
    if not config.dry_run:
        write_jsonl(
            quarantine_path,
            [
                {
                    "file": str(record.file_path),
                    "source_id": record.source_id,
                    "source_file_id": record.source_file_id,
                    "fingerprint": fingerprint,
                    "last_error": last_error_message,
                    "attempts_history": attempts_history,
                }
            ],
        )
    upsert_file_state(
        conn,
        key,
        record,
        fingerprint,
        "failed",
        config.max_rule_attempts,
        output_path="",
        quarantine_path=final_quarantine_path,
        last_error=last_error_message[:4000],
    )
    print_log(f"Failed {record.file_path.name}; quarantine -> {quarantine_path}")
    return "failed"


def summarize_run(statuses: Sequence[str]) -> Dict[str, int]:
    return dict(Counter(statuses))


def run_normalizer(config: Config) -> int:
    init_state_db(config.state_db)
    llm = LlmClient(config)
    config.out_dir.mkdir(parents=True, exist_ok=True)

    pass_number = 0
    while True:
        pass_number += 1
        records = load_file_records(config)
        print_log(f"Pass {pass_number}: loaded {len(records)} file records from metadata DB")
        statuses: List[str] = []
        with sqlite_connect(config.state_db) as conn:
            for record in records:
                try:
                    status = process_one_file(config, llm, record, conn)
                except KeyboardInterrupt:
                    raise
                except Exception as exc:
                    key = file_key(record)
                    message = f"fatal file processing error: {type(exc).__name__}: {exc}"
                    log_event(conn, key, "fatal_exception", message)
                    print_log(message)
                    status = "fatal_error"
                statuses.append(status)
        summary = summarize_run(statuses)
        print_log(f"Pass {pass_number} summary: {summary}")

        if not config.watch:
            break
        if config.max_global_passes > 0 and pass_number >= config.max_global_passes:
            break
        time.sleep(config.watch_sleep_sec)

    return 0


def read_metadata_query(args: argparse.Namespace) -> str:
    if args.metadata_query_file:
        return read_text_file(Path(args.metadata_query_file))
    if args.metadata_query:
        return args.metadata_query
    return DEFAULT_METADATA_QUERY


def normalize_api_url(url: str) -> str:
    value = url.strip().rstrip("/")
    if value.endswith("/chat/completions"):
        return value
    if value.endswith("/v1"):
        return value + "/chat/completions"
    return value + "/chat/completions"


