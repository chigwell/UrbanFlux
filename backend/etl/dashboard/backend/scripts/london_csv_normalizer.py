def build_config(args: argparse.Namespace) -> Config:
    if args.self_test:
        dummy = Path("/tmp/nonexistent.sqlite")
    else:
        if not args.metadata_db:
            raise SystemExit("--metadata-db is required unless --self-test is used")
        dummy = Path(args.metadata_db)

    return Config(
        metadata_db=dummy,
        metadata_query=read_metadata_query(args),
        csv_root=Path(args.csv_root).resolve(),
        out_dir=Path(args.out_dir).resolve(),
        state_db=Path(args.state_db).resolve(),
        api_url=normalize_api_url(args.api_url),
        api_key_env=args.api_key_env,
        model=args.model,
        temperature=args.temperature,
        max_tokens=args.max_tokens,
        request_timeout_sec=args.request_timeout_sec,
        max_http_retries=args.max_http_retries,
        sample_rows=args.sample_rows,
        raw_head_rows=args.raw_head_rows,
        max_rule_attempts=args.max_rule_attempts,
        max_global_passes=args.max_global_passes,
        watch=args.watch,
        watch_sleep_sec=args.watch_sleep_sec,
        force=args.force,
        dry_run=args.dry_run,
        limit_files=args.limit_files,
        use_response_format=not args.no_response_format,
        verify_with_llm=not args.no_llm_verifier,
        verifier_sample_size=args.verifier_sample_size,
        verifier_confidence_threshold=args.verifier_confidence_threshold,
        encodings=[item.strip() for item in args.encodings.split(",") if item.strip()],
        max_prompt_chars=args.max_prompt_chars,
        max_validation_errors=args.max_validation_errors,
        fail_on_llm_verifier_error=args.fail_on_llm_verifier_error,
    )


