def sample_output_rows_for_verifier(rows: Sequence[Mapping[str, str]], limit: int) -> List[Dict[str, str]]:
    if not rows:
        return []
    picked: List[Mapping[str, str]] = []
    picked.extend(rows[: min(5, len(rows))])
    weak = [
        row
        for row in rows
        if row.get("_normalizer_date_status") != "resolved" or row.get("_normalizer_area_kind") == "no_specific_area"
    ]
    picked.extend(weak[: max(0, limit // 2)])
    if len(picked) < limit:
        remaining = [row for row in rows if row not in picked]
        random.shuffle(remaining)
        picked.extend(remaining[: limit - len(picked)])

    unique: List[Mapping[str, str]] = []
    seen = set()
    for row in picked:
        key = (row.get("_normalizer_input_row_number", ""), row.get("_normalizer_measure_column", ""))
        if key in seen:
            continue
        seen.add(key)
        unique.append(row)
        if len(unique) >= limit:
            break

    compact: List[Dict[str, str]] = []
    for row in unique:
        compact.append({key: truncate(value, 180) for key, value in row.items() if value})
    return compact


def summarize_validation(result: ApplyResult) -> Dict[str, Any]:
    date_statuses = Counter(row.get("_normalizer_date_status", "") for row in result.output_rows)
    area_kinds = Counter(row.get("_normalizer_area_kind", "") for row in result.output_rows)
    return {
        "input_data_row_count": result.input_data_row_count,
        "output_row_count": len(result.output_rows),
        "skipped_row_count": len(result.skipped_rows),
        "validation_error_count": len(result.validation_errors),
        "first_validation_errors": result.validation_errors[:10],
        "date_status_counts": dict(date_statuses),
        "area_kind_counts": dict(area_kinds),
    }


