"""
LLM-assisted normalizer for heterogeneous London CSV datasets.

Goal:
- read file metadata from a local SQLite database;
- profile each CSV without assuming a stable schema;
- ask an OpenAI-compatible Chat Completions endpoint for a deterministic JSON rule;
- apply that rule locally, not by letting the model mutate data directly;
- retry with validation and verifier errors until the file is normalized or quarantined;
- write normalized CSVs with row-level date range and London/UK area fields.

The generated LLM rule is deliberately declarative. This is safer and more repeatable
than executing arbitrary Python generated by a model.
"""

