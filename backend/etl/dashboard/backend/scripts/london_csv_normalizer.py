def record_context_text(record: Optional[FileRecord]) -> str:
    if record is None:
        return ""
    pieces = [record.file_path.name, record.source_description]
    pieces.extend(f"{key}: {value}" for key, value in sorted(record.metadata.items()))
    return "\n".join(pieces)


def is_census_context(record: Optional[FileRecord]) -> bool:
    text = record_context_text(record).lower()
    return "census" in text and any(year in text for year in ("1991", "2001", "2011", "2021"))


def preferred_date_interpretation(record: Optional[FileRecord]) -> str:
    if is_census_context(record):
        return "uk_census_day"
    return "auto"


def extract_date_token(text: str) -> str:
    match = DATE_TOKEN_RE.search(text)
    return normalize_space(match.group(0)) if match else normalize_space(text)


def strip_date_tokens_from_header(header: str) -> str:
    value = DATE_TOKEN_RE.sub(" ", header)
    value = re.sub(r"\s*[-|:/,;()\[\]]\s*", " ", value)
    value = normalize_space(value)
    return value or normalize_space(header)


def detect_date_header_columns(
    table: PreparedTable,
    record: Optional[FileRecord] = None,
    sample_limit: int = 80,
) -> List[Dict[str, Any]]:
    interpretation = preferred_date_interpretation(record)
    candidates: List[Dict[str, Any]] = []
    for header in table.headers:
        if header.startswith("_normalizer_"):
            continue
        parsed = parse_date_range(header, source=f"header:{header}", interpretation=interpretation)
        if parsed.status != "resolved":
            continue
        non_empty = sum(1 for row in table.rows[:sample_limit] if normalize_space(row.get(header, "")))
        if non_empty == 0:
            continue
        date_raw = extract_date_token(header)
        candidates.append(
            {
                "column": header,
                "measure_name": strip_date_tokens_from_header(header),
                "date_raw": date_raw,
                "parsed_start": parsed.start,
                "parsed_end": parsed.end,
                "parsed_precision": parsed.precision,
                "non_empty_sample_count": non_empty,
            }
        )
    return candidates


def detect_row_area_columns(table: PreparedTable, sample_limit: int = 80) -> List[Dict[str, Any]]:
    candidates: List[Dict[str, Any]] = []
    for header in table.headers:
        if header.startswith("_normalizer_"):
            continue
        values = [normalize_space(row.get(header, "")) for row in table.rows[:sample_limit]]
        non_empty = [value for value in values if value]
        if not non_empty:
            continue

        hits: List[AreaResolution] = []
        canonical_names = set()
        for value in non_empty:
            resolved = normalize_area_text(value, allow_custom_area=False)
            if resolved.kind in {"london_borough", "city_of_london", "london_all", "uk_all", "england_all"}:
                hits.append(resolved)
                canonical_names.add(f"{resolved.kind}:{resolved.name}")

        hit_count = len(hits)
        hit_ratio = hit_count / max(len(non_empty), 1)
        header_key = normalise_lookup_key(header)
        header_bonus = 0.15 if any(token in header_key.split() for token in {"area", "borough", "authority", "name"}) else 0.0
        # Require several recognised geography values and more than one geography.
        # This avoids replacing a legitimate constant London-wide rule just because
        # a file has one repeated "London" column.
        if hit_count >= 2 and len(canonical_names) >= 2 and hit_ratio >= 0.35:
            candidates.append(
                {
                    "column": header,
                    "sample_values": top_values(non_empty, limit=8),
                    "matched_sample_count": hit_count,
                    "non_empty_sample_count": len(non_empty),
                    "distinct_matched_area_count": len(canonical_names),
                    "score": round(min(1.0, hit_ratio + header_bonus), 3),
                }
            )

    candidates.sort(
        key=lambda item: (
            float(item["score"]),
            int(item["distinct_matched_area_count"]),
            int(item["matched_sample_count"]),
        ),
        reverse=True,
    )
    return candidates


def build_deterministic_preflight(record: FileRecord, table: PreparedTable) -> Dict[str, Any]:
    date_header_columns = detect_date_header_columns(table, record=record)
    row_area_columns = detect_row_area_columns(table)
    return {
        "recommended_date_interpretation": preferred_date_interpretation(record),
        "date_header_column_candidates": date_header_columns,
        "row_area_column_candidates": row_area_columns,
        "must_unpivot_date_headers": len(date_header_columns) >= 2,
        "must_use_row_area_column": bool(row_area_columns),
    }


def build_csv_profile(
    record: FileRecord,
    raw: RawCsv,
    table: PreparedTable,
    config: Config,
    previous_attempts: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    sample_rows = table.rows[: config.sample_rows]

    column_profiles: List[Dict[str, Any]] = []
    for header in table.headers:
        values = [row.get(header, "") for row in sample_rows]
        non_empty = [v for v in values if normalize_space(v)]
        date_hit_count = 0
