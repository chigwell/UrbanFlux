def load_file_records(config: Config) -> List[FileRecord]:
    with sqlite_connect(config.metadata_db) as conn:
        rows = conn.execute(config.metadata_query).fetchall()

    records: List[FileRecord] = []
    for idx, row in enumerate(rows):
        keys = set(row.keys())
        if "file_path" not in keys:
            raise RuntimeError("metadata query must return a file_path column")
        raw_path = str(row["file_path"] or "").strip()
        if not raw_path:
            continue
        path = Path(raw_path)
        if not path.is_absolute():
            path = config.csv_root / path
        path = path.resolve()
        source_id = str(row["source_id"] if "source_id" in keys and row["source_id"] is not None else "")
        source_file_id = str(row["source_file_id"] if "source_file_id" in keys and row["source_file_id"] is not None else idx)
        source_description = str(
            row["source_description"] if "source_description" in keys and row["source_description"] is not None else ""
        )
        metadata = {key: str(row[key]) for key in keys if row[key] is not None}
        records.append(
            FileRecord(
                source_id=source_id,
                source_file_id=source_file_id,
                file_path=path,
                source_description=source_description,
                metadata=metadata,
            )
        )

    if config.limit_files > 0:
        records = records[: config.limit_files]
    return records


def top_values(values: Iterable[str], limit: int = 8) -> List[str]:
    counter: Counter[str] = Counter(v for v in values if normalize_space(v))
    return [truncate(value, 120) for value, _ in counter.most_common(limit)]


MONTH_TOKEN_RE = (
    r"jan(?:uary)?|feb(?:ruary)?|mar(?:ch)?|apr(?:il)?|may|jun(?:e)?|"
    r"jul(?:y)?|aug(?:ust)?|sep(?:t(?:ember)?)?|oct(?:ober)?|nov(?:ember)?|dec(?:ember)?"
)
YEAR_TOKEN_RE = r"(?:19\d{2}|20\d{2})"
DATE_TOKEN_RE = re.compile(
    rf"\b(?:"
    rf"\d{{1,2}}\s+(?:{MONTH_TOKEN_RE})\s+\d{{2,4}}|"
    rf"(?:{MONTH_TOKEN_RE})\s+\d{{1,2}},?\s+\d{{2,4}}|"
    rf"\d{{4}}[-/]\d{{1,2}}[-/]\d{{1,2}}|"
    rf"\d{{1,2}}[-/.]\d{{1,2}}[-/.]\d{{2,4}}|"
    rf"Q[1-4]\s*[-/]?\s*{YEAR_TOKEN_RE}|"
    rf"{YEAR_TOKEN_RE}\s*[-/]?\s*Q[1-4]|"
    rf"(?:FY|F/Y|financial year|tax year)?\s*{YEAR_TOKEN_RE}\s*[/\-]\s*(?:\d{{2}}|{YEAR_TOKEN_RE})|"
    rf"{YEAR_TOKEN_RE}"
    rf")\b",
    re.I,
)

