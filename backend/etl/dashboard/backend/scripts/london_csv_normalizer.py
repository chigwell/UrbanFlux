def normalize_area_text(raw: str, allow_custom_area: bool = True) -> AreaResolution:
    original = normalize_space(raw)
    if not original:
        return AreaResolution(
            kind="no_specific_area",
            name="",
            raw=raw,
            source="",
            reason="No area text was present in the selected source.",
            confidence=1.0,
        )

    key = normalise_lookup_key(original)
    if key in WHOLE_AREA_ALIASES:
        kind, name = WHOLE_AREA_ALIASES[key]
        return AreaResolution(kind, name, original, "", f"Matched whole-area alias '{original}'.", 1.0)
    if key in BOROUGH_ALIASES:
        kind, name = BOROUGH_ALIASES[key]
        return AreaResolution(kind, name, original, "", f"Matched London borough alias '{original}'.", 1.0)

    # Embedded aliases, e.g. "London Borough of Camden - total".
    for alias_key, (kind, name) in sorted(BOROUGH_ALIASES.items(), key=lambda item: len(item[0]), reverse=True):
        if alias_key and re.search(rf"\b{re.escape(alias_key)}\b", key):
            return AreaResolution(kind, name, original, "", f"Matched embedded borough alias '{alias_key}'.", 0.92)

    for alias_key, (kind, name) in sorted(WHOLE_AREA_ALIASES.items(), key=lambda item: len(item[0]), reverse=True):
        if alias_key and re.search(rf"\b{re.escape(alias_key)}\b", key):
            return AreaResolution(kind, name, original, "", f"Matched embedded whole-area alias '{alias_key}'.", 0.9)

    # Conservative fuzzy match. Do not fuzzy-match very short text.
    if len(key) >= 5:
        candidate_keys = list(BOROUGH_ALIASES.keys())
        matches = get_close_matches(key, candidate_keys, n=1, cutoff=0.88)
        if matches:
            kind, name = BOROUGH_ALIASES[matches[0]]
            return AreaResolution(kind, name, original, "", f"Fuzzy-matched '{original}' to '{name}'.", 0.86)

    if allow_custom_area:
        custom_name = original.strip(" .,:;-/\\")
        return AreaResolution(
            kind="custom_london_area",
            name=custom_name,
            raw=original,
            source="",
            reason="The text did not match a canonical London borough, City of London, London-wide, England, or UK alias; kept as a custom London area.",
            confidence=0.55,
        )

    return AreaResolution(
        kind="no_specific_area",
        name="",
        raw=original,
        source="",
        reason="The selected area text did not match a supported canonical area and custom areas are disabled by the rule.",
        confidence=0.4,
    )


def last_day_of_month(year: int, month: int) -> int:
    return calendar.monthrange(year, month)[1]


def iso_date(value: dt.date) -> str:
    return value.isoformat()


def parse_iso_date(text: str) -> Optional[dt.date]:
    try:
        return dt.date.fromisoformat(text)
    except Exception:
        return None


def date_resolution_no_date(raw: str, source: str, reason: str) -> DateResolution:
    return DateResolution(
        status="no_date_in_available_context",
        start="",
        end="",
        precision="none",
        raw=raw,
        source=source,
        reason=reason or "No usable date was present in the selected source.",
    )


def make_date_resolution(
    start: dt.date,
    end: dt.date,
    precision: str,
    raw: str,
    source: str,
    reason: str,
) -> DateResolution:
    return DateResolution(
        status="resolved",
        start=iso_date(start),
        end=iso_date(end),
        precision=precision,
        raw=raw,
        source=source,
        reason=reason,
    )


def expand_two_digit_year(start_year: int, end_token: str) -> int:
    if len(end_token) == 4:
        return int(end_token)
    century = start_year // 100 * 100
    end_year = century + int(end_token)
    if end_year < start_year:
        end_year += 100
    return end_year


def parse_single_date(text: str, dayfirst: bool = True) -> Optional[dt.date]:
    value = normalize_space(text)
    value = value.strip(".,;:()[]{}")
    if not value:
        return None

    formats = [
        "%Y-%m-%d",
        "%d/%m/%Y" if dayfirst else "%m/%d/%Y",
        "%d-%m-%Y" if dayfirst else "%m-%d-%Y",
        "%d.%m.%Y" if dayfirst else "%m.%d.%Y",
        "%d %b %Y",
        "%d %B %Y",
        "%b %d %Y",
        "%B %d %Y",
    ]
    for fmt in formats:
        try:
            return dt.datetime.strptime(value, fmt).date()
        except ValueError:
            pass

    if dateutil_parser is not None:
        try:
            parsed = dateutil_parser.parse(value, dayfirst=dayfirst, fuzzy=True)
            return parsed.date()
        except Exception:
            return None

    return None


def parse_month_name_range(value: str, dayfirst: bool, raw: str, source: str) -> Optional[DateResolution]:
    month_regex = (
        r"\b(?P<month>jan(?:uary)?|feb(?:ruary)?|mar(?:ch)?|apr(?:il)?|may|jun(?:e)?|"
        r"jul(?:y)?|aug(?:ust)?|sep(?:t(?:ember)?)?|oct(?:ober)?|nov(?:ember)?|dec(?:ember)?)\b"
    )
    m = re.search(month_regex + r"[\s,/-]*(?P<year>19\d{2}|20\d{2})\b", value, re.I)
    if not m:
        m = re.search(r"\b(?P<year>19\d{2}|20\d{2})[\s,/-]*" + month_regex, value, re.I)
    if not m:
        return None

    month_name = m.group("month")[:3].lower()
    months = {
        "jan": 1,
        "feb": 2,
        "mar": 3,
        "apr": 4,
        "may": 5,
        "jun": 6,
        "jul": 7,
        "aug": 8,
        "sep": 9,
        "oct": 10,
        "nov": 11,
        "dec": 12,
    }
    month = months[month_name]
    year = int(m.group("year"))
    start = dt.date(year, month, 1)
    end = dt.date(year, month, last_day_of_month(year, month))
    return make_date_resolution(start, end, "month", raw, source, f"Parsed month/year from '{raw}'.")


def parse_date_range(
    raw: str,
    source: str,
    interpretation: str = "auto",
    dayfirst: bool = True,
    reason_when_missing: str = "",
) -> DateResolution:
    original = normalize_space(raw)
    # File names and some headers use underscores as separators; word-boundary
    # regexes would otherwise miss tokens like crime_2020.csv.
    text = normalize_space(re.sub(r"[_]+", " ", original))
    value = text.lower()
    value = value.replace("—", "-").replace("–", "-").replace("−", "-")

    if not original:
        return date_resolution_no_date(original, source, reason_when_missing)

    missing_tokens = {"n/a", "na", "not available", "unknown", "none", "all", "total"}
    if value.strip(" .:-_/\\") in missing_tokens:
        return date_resolution_no_date(original, source, reason_when_missing)

    if interpretation == "uk_census_day":
        years = sorted({int(year) for year in re.findall(r"\b(19\d{2}|20\d{2})\b", text)})
        if len(years) == 1 and years[0] in KNOWN_ENGLAND_WALES_CENSUS_DATES:
            census_day = KNOWN_ENGLAND_WALES_CENSUS_DATES[years[0]]
            return make_date_resolution(
                census_day,
                census_day,
                "census_day",
                original,
                source,
                f"Interpreted {years[0]} as an England and Wales population Census day in census context.",
            )

    census_day_match = re.search(
        rf"\bcensus\s+(?:day|night)\b[^0-9a-z]{{0,30}}(?P<date>\d{{1,2}}\s+(?:{MONTH_TOKEN_RE})\s+\d{{4}})",
        text,
        re.I,
    )
    if census_day_match:
        single = parse_single_date(census_day_match.group("date"), dayfirst=dayfirst)
        if single:
            return make_date_resolution(single, single, "census_day", original, source, "Parsed exact Census day from text.")

    week_ending = re.search(r"\b(?:week ending|week ended|w/e)\b\s*(?P<date>.+)$", text, re.I)
    if week_ending:
        end_date = parse_single_date(week_ending.group("date"), dayfirst=dayfirst)
        if end_date:
            start_date = end_date - dt.timedelta(days=6)
            return make_date_resolution(start_date, end_date, "week", original, source, "Parsed as a week-ending date.")

    week_commencing = re.search(r"\b(?:week commencing|week beginning|w/c)\b\s*(?P<date>.+)$", text, re.I)
    if week_commencing:
        start_date = parse_single_date(week_commencing.group("date"), dayfirst=dayfirst)
        if start_date:
            end_date = start_date + dt.timedelta(days=6)
            return make_date_resolution(start_date, end_date, "week", original, source, "Parsed as a week-commencing date.")

    # Explicit day-level date ranges before financial-year parsing, so ISO dates
    # such as 2020-03-01 are not mistaken for 2020/03 fiscal years.
    parts = re.split(r"\s+(?:to|until|through|-|–|—)\s+", text, maxsplit=1, flags=re.I)
    if len(parts) == 2:
        start_date = parse_single_date(parts[0], dayfirst=dayfirst)
        end_date = parse_single_date(parts[1], dayfirst=dayfirst)
        if start_date and end_date and end_date >= start_date:
            return make_date_resolution(start_date, end_date, "date_range", original, source, "Parsed as an explicit date range.")

    looks_like_day_date = bool(
        re.search(r"\b\d{4}[-/]\d{1,2}[-/]\d{1,2}\b", text)
        or re.search(r"\b\d{1,2}[-/.]\d{1,2}[-/.]\d{2,4}\b", text)
        or re.search(
            r"\b\d{1,2}\s+(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\s+\d{2,4}\b",
            text,
            re.I,
        )
        or re.search(
            r"\b(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\s+\d{1,2},?\s+\d{2,4}\b",
            text,
            re.I,
        )
    )
    if looks_like_day_date:
        single = parse_single_date(text, dayfirst=dayfirst)
        if single:
            return make_date_resolution(single, single, "day", original, source, "Parsed as a single date.")

        embedded_day_match = re.search(
            rf"\b(?P<date>\d{{1,2}}\s+(?:{MONTH_TOKEN_RE})\s+\d{{2,4}}|(?:{MONTH_TOKEN_RE})\s+\d{{1,2}},?\s+\d{{2,4}}|\d{{4}}[-/]\d{{1,2}}[-/]\d{{1,2}}|\d{{1,2}}[-/.]\d{{1,2}}[-/.]\d{{2,4}})\b",
            text,
            re.I,
        )
        if embedded_day_match and ("census day" in value or len(text) <= 120):
            single = parse_single_date(embedded_day_match.group("date"), dayfirst=dayfirst)
            if single:
                precision = "census_day" if "census day" in value else "day"
                return make_date_resolution(single, single, precision, original, source, "Parsed embedded day-level date from text.")

    # ISO-like YYYY-MM month before financial-year parsing; otherwise 2020-03
    # would be read as a 2020/03 financial-year token. Slash years such as
    # 2019/20 remain financial-year candidates later.
    ym_hyphen = re.search(r"\b(?P<year>19\d{2}|20\d{2})-(?P<month>0?[1-9]|1[0-2])\b", text)
    if ym_hyphen and not re.search(r"\b\d{4}-\d{1,2}-\d{1,2}\b", text):
        year = int(ym_hyphen.group("year"))
        month = int(ym_hyphen.group("month"))
        return make_date_resolution(
            dt.date(year, month, 1),
            dt.date(year, month, last_day_of_month(year, month)),
            "month",
            original,
            source,
            "Parsed YYYY-MM as a month.",
        )

    # UK financial years: FY2019/20, 2019/20, 2019-20 when interpretation requests it.
    fy = re.search(
        r"\b(?:fy|f/y|financial year|tax year|year ending|year ended|ye)?\s*"
        r"(?P<start>19\d{2}|20\d{2})\s*[/\-]\s*(?P<end>\d{2}|19\d{2}|20\d{2})\b",
        text,
        re.I,
    )
    if fy:
        start_year = int(fy.group("start"))
        end_year = expand_two_digit_year(start_year, fy.group("end"))
        looks_financial = (
            interpretation == "financial_year_uk"
            or bool(re.search(r"\b(?:fy|financial|tax|year ending|year ended|ye)\b", text, re.I))
            or len(fy.group("end")) == 2
            or "/" in fy.group(0)
        )
        if looks_financial:
            start = dt.date(start_year, 4, 1)
            end = dt.date(end_year, 3, 31)
            if end >= start:
                return make_date_resolution(start, end, "financial_year_uk", original, source, "Parsed as a UK financial year.")
        if end_year >= start_year:
            start = dt.date(start_year, 1, 1)
            end = dt.date(end_year, 12, 31)
            return make_date_resolution(start, end, "year_range", original, source, "Parsed as a calendar year range.")

    # Calendar year ranges: 2018 to 2020, 2018 - 2020.
    yr_range = re.search(
        r"\b(?P<start>19\d{2}|20\d{2})\s*(?:to|until|through|-)\s*(?P<end>19\d{2}|20\d{2})\b",
        text,
        re.I,
    )
    if yr_range:
        start_year = int(yr_range.group("start"))
        end_year = int(yr_range.group("end"))
        if end_year >= start_year:
            return make_date_resolution(
                dt.date(start_year, 1, 1),
                dt.date(end_year, 12, 31),
                "year_range",
                original,
                source,
                "Parsed as a calendar year range.",
            )

    # Quarters.
    q_match = re.search(r"\bQ(?P<q>[1-4])\s*[-/]?\s*(?P<year>19\d{2}|20\d{2})\b", text, re.I)
    if not q_match:
        q_match = re.search(r"\b(?P<year>19\d{2}|20\d{2})\s*[-/]?\s*Q(?P<q>[1-4])\b", text, re.I)
    if q_match:
        year = int(q_match.group("year"))
        quarter = int(q_match.group("q"))
        if interpretation == "financial_year_uk":
            financial_quarter_months = {1: (4, 6), 2: (7, 9), 3: (10, 12), 4: (1, 3)}
            start_month, end_month = financial_quarter_months[quarter]
            start_year = year if quarter in {1, 2, 3} else year + 1
            end_year = start_year
        else:
            start_month = (quarter - 1) * 3 + 1
            end_month = start_month + 2
            start_year = end_year = year
        start = dt.date(start_year, start_month, 1)
        end = dt.date(end_year, end_month, last_day_of_month(end_year, end_month))
        return make_date_resolution(start, end, "quarter", original, source, "Parsed as a quarter.")

    # YYYY-MM / YYYY/MM as month.
    ym = re.search(r"\b(?P<year>19\d{2}|20\d{2})[-/](?P<month>0?[1-9]|1[0-2])\b", text)
    if ym and not re.search(r"\b\d{4}[-/]\d{1,2}[-/]\d{1,2}\b", text):
        year = int(ym.group("year"))
        month = int(ym.group("month"))
        return make_date_resolution(
            dt.date(year, month, 1),
            dt.date(year, month, last_day_of_month(year, month)),
            "month",
            original,
            source,
            "Parsed YYYY-MM as a month.",
        )

    month_range = parse_month_name_range(text, dayfirst=dayfirst, raw=original, source=source)
    if month_range:
        return month_range

    # Bare year.
    year_match = re.fullmatch(r".*?\b(?P<year>19\d{2}|20\d{2})\b.*?", text)
    if year_match:
        year = int(year_match.group("year"))
        if interpretation == "uk_census_day" and year in KNOWN_ENGLAND_WALES_CENSUS_DATES:
            census_day = KNOWN_ENGLAND_WALES_CENSUS_DATES[year]
            return make_date_resolution(
                census_day,
                census_day,
                "census_day",
                original,
                source,
                f"Mapped Census year {year} to the England and Wales Census day.",
            )
        return make_date_resolution(
            dt.date(year, 1, 1),
            dt.date(year, 12, 31),
            "year",
            original,
            source,
            "Parsed as a calendar year.",
        )

    return date_resolution_no_date(original, source, reason_when_missing)


def detect_dialect(sample: str) -> csv.Dialect:
    try:
        return csv.Sniffer().sniff(sample, delimiters=[",", ";", "\t", "|"])
    except Exception:
        class FallbackDialect(csv.excel):
            delimiter = ","
            quotechar = '"'
        return FallbackDialect


def read_csv_raw(path: Path, encodings: Sequence[str]) -> RawCsv:
    data = path.read_bytes()
    last_error: Optional[Exception] = None
    for encoding in encodings:
        try:
            text = data.decode(encoding)
            sample = text[:65_536]
            dialect = detect_dialect(sample)
            reader = csv.reader(io.StringIO(text, newline=""), dialect=dialect)
            rows = [[str(cell) for cell in row] for row in reader]
            dialect_name = getattr(dialect, "__name__", dialect.__class__.__name__)
            return RawCsv(
                path=path,
                encoding=encoding,
                dialect_name=dialect_name,
                delimiter=getattr(dialect, "delimiter", ","),
                quotechar=getattr(dialect, "quotechar", '"'),
                raw_rows=rows,
            )
        except Exception as exc:
            last_error = exc
            continue
    raise RuntimeError(f"Could not read CSV {path}: {last_error}")


def make_unique_headers(cells: Sequence[str]) -> List[str]:
    seen: Counter[str] = Counter()
    headers: List[str] = []
    for idx, cell in enumerate(cells):
        name = normalize_space(cell).lstrip("\ufeff")
        if not name:
            name = f"column_{idx + 1}"
        seen[name] += 1
        if seen[name] > 1:
            name = f"{name}__{seen[name]}"
        headers.append(name)
    if not headers:
        headers = ["column_1"]
    return headers


def combine_header_rows(raw_rows: Sequence[Sequence[str]], header_row_indices: Sequence[int]) -> List[str]:
    max_len = 0
    for idx in header_row_indices:
        if 0 <= idx < len(raw_rows):
            max_len = max(max_len, len(raw_rows[idx]))
    if max_len == 0:
        return ["column_1"]

    combined: List[str] = []
    for col_idx in range(max_len):
        parts: List[str] = []
        for row_idx in header_row_indices:
            if 0 <= row_idx < len(raw_rows) and col_idx < len(raw_rows[row_idx]):
                value = normalize_space(raw_rows[row_idx][col_idx])
                if value and value not in parts:
                    parts.append(value)
        combined.append(" | ".join(parts) if parts else f"column_{col_idx + 1}")
    return make_unique_headers(combined)


def default_layout(raw_rows: Sequence[Sequence[str]]) -> Dict[str, Any]:
    # Default is conservative: first row is header, second row starts data.
    if not raw_rows:
        return {
            "header_row_indices": [0],
            "data_start_row_index": 1,
            "skip_empty_rows": True,
            "skip_row_regexes": [],
        }
    return {
        "header_row_indices": [0],
        "data_start_row_index": 1,
        "skip_empty_rows": True,
        "skip_row_regexes": [],
    }


def sanitize_layout(layout: Optional[Mapping[str, Any]], raw_rows: Sequence[Sequence[str]]) -> Dict[str, Any]:
    base = default_layout(raw_rows)
    if not layout:
        return base

    header_row_indices = layout.get("header_row_indices", base["header_row_indices"])
    if not isinstance(header_row_indices, list) or not header_row_indices:
        header_row_indices = base["header_row_indices"]
    clean_indices: List[int] = []
    for value in header_row_indices:
        try:
            idx = int(value)
        except Exception:
            continue
        if 0 <= idx < max(len(raw_rows), 1):
            clean_indices.append(idx)
    if not clean_indices:
        clean_indices = base["header_row_indices"]

    try:
        data_start_row_index = int(layout.get("data_start_row_index", max(clean_indices) + 1))
    except Exception:
        data_start_row_index = max(clean_indices) + 1
    data_start_row_index = max(data_start_row_index, max(clean_indices) + 1)

    skip_regexes = layout.get("skip_row_regexes", [])
    if not isinstance(skip_regexes, list):
        skip_regexes = []

    return {
        "header_row_indices": clean_indices,
        "data_start_row_index": data_start_row_index,
        "skip_empty_rows": bool(layout.get("skip_empty_rows", True)),
        "skip_row_regexes": [str(x) for x in skip_regexes if str(x).strip()],
    }


def prepare_table(raw: RawCsv, layout: Optional[Mapping[str, Any]] = None) -> PreparedTable:
    clean_layout = sanitize_layout(layout, raw.raw_rows)
    headers = combine_header_rows(raw.raw_rows, clean_layout["header_row_indices"])
    rows: List[OrderedDict[str, str]] = []
    skipped: List[Dict[str, Any]] = []
    skip_patterns: List[re.Pattern[str]] = []
    for pattern in clean_layout["skip_row_regexes"]:
        try:
            skip_patterns.append(re.compile(pattern, re.I))
        except re.error as exc:
            skipped.append({"raw_row_number": None, "reason": f"Invalid skip regex {pattern!r}: {exc}"})

    for raw_index, cells in enumerate(raw.raw_rows):
        if raw_index < clean_layout["data_start_row_index"]:
            continue
        normalized_cells = [normalize_space(cell) for cell in cells]
        if clean_layout["skip_empty_rows"] and not any(normalized_cells):
            skipped.append({"raw_row_number": raw_index + 1, "reason": "empty row"})
            continue
        joined = " | ".join(normalized_cells)
        if any(pattern.search(joined) for pattern in skip_patterns):
            skipped.append({"raw_row_number": raw_index + 1, "reason": "matched layout skip_row_regexes"})
            continue

        row: OrderedDict[str, str] = OrderedDict()
        for col_idx, header in enumerate(headers):
            row[header] = normalized_cells[col_idx] if col_idx < len(normalized_cells) else ""
        if len(normalized_cells) > len(headers):
            for extra_idx in range(len(headers), len(normalized_cells)):
                row[f"extra_column_{extra_idx + 1}"] = normalized_cells[extra_idx]
        row["_normalizer_raw_row_number"] = str(raw_index + 1)
        rows.append(row)

    return PreparedTable(headers=headers, rows=rows, skipped_raw_rows=skipped, layout=clean_layout)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def rule_hash(rule: Mapping[str, Any]) -> str:
    payload = json.dumps(rule, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def file_key(record: FileRecord) -> str:
    text = f"{record.source_id}\n{record.source_file_id}\n{record.file_path.resolve()}"
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


